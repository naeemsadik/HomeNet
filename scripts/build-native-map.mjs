#!/usr/bin/env node
// Copies Leaflet and its cluster plugin (the installed versions, from node_modules) into a module
// the Android app's map page is built from: the app's WebView has no Metro to bundle them, and
// loading them from a CDN would make the map depend on a third party being reachable.
//
// Run after upgrading leaflet or leaflet.markercluster:  npm run map:native
// A test fails while the copy is older than the installed packages.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (path) => readFileSync(join(root, "node_modules", path), "utf8");
const version = (pkg) => JSON.parse(read(`${pkg}/package.json`)).version;

const out = join(root, "src/features/property/components/leafletAssets.generated.ts");
// Leaflet's minified file carries its own @preserve notice. The cluster plugin's does not, so its
// MIT notice goes in front of the code, inside the string the app ships (a minifier keeps strings).
const clusterNotice = `/*! leaflet.markercluster ${version("leaflet.markercluster")}\n${read("leaflet.markercluster/MIT-LICENCE.txt").trim()}\n*/\n`;
const constants = {
  LEAFLET_VERSION: version("leaflet"),
  MARKERCLUSTER_VERSION: version("leaflet.markercluster"),
  LEAFLET_JS: read("leaflet/dist/leaflet.js"),
  LEAFLET_CSS: read("leaflet/dist/leaflet.css"),
  MARKERCLUSTER_JS: clusterNotice + read("leaflet.markercluster/dist/leaflet.markercluster.js"),
  MARKERCLUSTER_CSS: read("leaflet.markercluster/dist/MarkerCluster.css"),
};

const body = Object.entries(constants)
  .map(([name, value]) => `export const ${name} = ${JSON.stringify(value)};`)
  .join("\n");

writeFileSync(
  out,
  `// Generated by scripts/build-native-map.mjs from leaflet@${constants.LEAFLET_VERSION} and\n` +
    `// leaflet.markercluster@${constants.MARKERCLUSTER_VERSION} (BSD-2-Clause and MIT; their notices are\n` +
    `// kept in the code below). Do not edit: run \`npm run map:native\`.\n` +
    `/* eslint-disable */\n${body}\n`,
);
console.log(`Wrote ${out.replace(root + "/", "")} (leaflet ${constants.LEAFLET_VERSION}, markercluster ${constants.MARKERCLUSTER_VERSION})`);
